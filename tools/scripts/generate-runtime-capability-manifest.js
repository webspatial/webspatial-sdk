const fs = require('fs')
const path = require('path')
const ts = require('typescript')

const repoRoot = path.resolve(__dirname, '..', '..')
const keysPath = path.join(repoRoot, 'packages/core/src/runtime/keys.ts')
const sourcePath = path.join(
  repoRoot,
  'packages/visionOS/runtime-capabilities.json',
)
const packagePath = path.join(repoRoot, 'packages/visionOS/package.json')
const outputPath = path.join(
  repoRoot,
  'packages/visionOS/web-spatial/RuntimeCapabilityManifest.generated.swift',
)

function loadTypeScriptModule(filePath) {
  const source = fs.readFileSync(filePath, 'utf8')
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: filePath,
  }).outputText
  const moduleExports = {}
  const evaluate = new Function('exports', compiled)
  evaluate(moduleExports)
  return moduleExports
}

function validateSource(source, registry) {
  if (source.manifestVersion !== 1) {
    throw new Error('visionOS manifest source must use manifestVersion 1.')
  }
  if (source.runtime?.type !== 'visionos') {
    throw new Error(
      'visionOS manifest source must declare runtime.type visionos.',
    )
  }
  if (!Array.isArray(source.supported)) {
    throw new Error('visionOS manifest source supported must be an array.')
  }

  const known = new Set(registry.TOP_LEVEL_KEYS)
  for (const [name, tokens] of Object.entries(registry.SUB_TOKENS_BY_NAME)) {
    for (const token of tokens) {
      known.add(`${name}:${token}`)
    }
  }

  const seen = new Set()
  for (const entry of source.supported) {
    if (typeof entry !== 'string' || !known.has(entry)) {
      throw new Error(`Unknown visionOS capability entry: ${String(entry)}`)
    }
    if (seen.has(entry)) {
      throw new Error(`Duplicate visionOS capability entry: ${entry}`)
    }
    seen.add(entry)
  }

  const sorted = [...source.supported].sort()
  if (JSON.stringify(sorted) !== JSON.stringify(source.supported)) {
    throw new Error(
      'visionOS capability entries must use canonical lexicographic order.',
    )
  }
}

function renderSwift(source, packageVersion) {
  const supported = source.supported
    .map(entry => `        ${JSON.stringify(entry)},`)
    .join('\n')

  return `// Generated by tools/scripts/generate-runtime-capability-manifest.js.
// Edit packages/visionOS/runtime-capabilities.json, then regenerate this file.

import Foundation
@preconcurrency import WebKit

enum RuntimeCapabilityManifestProvider {
    static let manifestVersion = ${source.manifestVersion}
    static let runtimeType = ${JSON.stringify(source.runtime.type)}
    static let packageVersion = ${JSON.stringify(packageVersion)}
    static let supported = [
${supported}
    ]

    static func manifestDictionary() -> [String: Any] {
        let configuredVersion = pwaManager.getShellVersion()
        let runtimeVersion = configuredVersion == "WS_SHELL_VERSION"
            ? packageVersion
            : configuredVersion
        let configuredBuildId = pwaManager.getRuntimeBuildId()
        let runtimeBuildId = configuredBuildId == "package-WS_SHELL_VERSION"
            ? "package-\\(packageVersion)"
            : configuredBuildId

        return [
            "manifestVersion": manifestVersion,
            "runtime": [
                "type": runtimeType,
                "version": runtimeVersion,
                "buildId": runtimeBuildId,
            ],
            "supported": supported,
        ]
    }

    static func injectionSource() -> String {
        let data = try! JSONSerialization.data(
            withJSONObject: manifestDictionary(),
            options: [.sortedKeys]
        )
        let json = String(decoding: data, as: UTF8.self)
        return """
        (() => {
          const manifest = \\(json);
          Object.freeze(manifest.runtime);
          Object.freeze(manifest.supported);
          Object.freeze(manifest);
          const install = target => {
            if (
              !target ||
              Object.prototype.hasOwnProperty.call(
                target,
                "__webspatialCapabilities",
              )
            ) {
              return;
            }
            Object.defineProperty(target, "__webspatialCapabilities", {
              value: manifest,
              writable: false,
              configurable: false,
            });
          };

          install(globalThis);

          const nativeOpen = globalThis.open;
          if (typeof nativeOpen === "function") {
            globalThis.open = function(...args) {
              const child = Reflect.apply(nativeOpen, this, args);
              try {
                install(child);
              } catch {
                // Cross-origin windows are intentionally left untouched.
              }
              return child;
            };
          }
        })();
        """
    }

    static func makeUserScript() -> WKUserScript {
        return WKUserScript(
            source: injectionSource(),
            injectionTime: .atDocumentStart,
            forMainFrameOnly: false
        )
    }
}
`
}

const registry = loadTypeScriptModule(keysPath)
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'))
const packageJson = JSON.parse(fs.readFileSync(packagePath, 'utf8'))
validateSource(source, registry)
const expected = renderSwift(source, packageJson.version)

if (process.argv.includes('--check')) {
  const actual = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, 'utf8')
    : ''
  if (actual !== expected) {
    throw new Error(
      'Generated visionOS capability manifest is stale. Run pnpm generate:runtime-capabilities.',
    )
  }
  console.log('visionOS runtime capability manifest is valid and up to date.')
} else {
  fs.writeFileSync(outputPath, expected)
  console.log(`Generated ${path.relative(repoRoot, outputPath)}`)
}
